//! Frida bridge (plan feature 12, slice 1): spawn/attach with ObjC/Swift
//! method tracing, captured calls promoted to provenance-carrying facts.
//!
//! The bridge generates a Frida agent script (TypeScript/JS), drives
//! `frida` CLI spawn+attach, captures method-call events from stdout,
//! and parses them into `MethodCall` records. Requires `frida` on PATH
//! — typed error when absent; every other failure is reported, never
//! fabricated. Method-call facts carry `frida_v1` provenance.

use std::path::Path;
use std::process::Command;

/// One captured ObjC/Swift method invocation.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
pub struct MethodCall {
    pub class_name: String,
    pub method_name: String,
    pub is_class_method: bool,
    pub args: Vec<String>,
}

/// Result of a Frida session.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
pub struct FridaReport {
    pub target: String,
    pub calls: Vec<MethodCall>,
    pub modules: Vec<String>,
}

/// True when the `frida` CLI is available.
pub fn frida_available() -> bool {
    Command::new("which")
        .arg("frida")
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false)
}

/// Generate a Frida agent script that traces ObjC method calls on the
/// given classes (or all classes when the list is empty) and prints
/// structured events to stdout: `DAMSEL_FRIDA_CALL class method +/- args…`
pub fn generate_trace_script(classes: &[&str], max_calls: usize) -> String {
    let class_filter = if classes.is_empty() {
        "null".to_string()
    } else {
        format!(
            "[{}]",
            classes
                .iter()
                .map(|c| format!("\"{c}\""))
                .collect::<Vec<_>>()
                .join(", ")
        )
    };
    let mut script = String::new();
    script.push_str("// Generated by damsel (frida_v1): ObjC method tracer.\n");
    script.push_str("// Events print as: DAMSEL_FRIDA_CALL <class> <method> <+/-> <args...>\n");
    script.push_str(&format!("const CLASS_FILTER = {class_filter};\n"));
    script.push_str(&format!("const MAX_CALLS = {max_calls};\n"));
    script.push_str("let callCount = 0;\n\n");
    script.push_str("if (ObjC.available) {\n");
    script.push_str("    send({ kind: \"objc_available\", modules: Process.enumerateModules().map(m => m.name) });\n");
    script.push_str("    const classes = CLASS_FILTER\n");
    script.push_str("        ? CLASS_FILTER.map(n => ObjC.classes[n]).filter(c => c)\n");
    script
        .push_str("        : Object.keys(ObjC.classes).slice(0, 50).map(n => ObjC.classes[n]);\n");
    script.push_str("    for (const cls of classes) {\n");
    script.push_str("        try {\n");
    script.push_str("            const methods = cls.$ownMethods;\n");
    script.push_str("            for (const methodName of methods) {\n");
    script.push_str("                try {\n");
    script.push_str("                    const isClassMethod = methodName.startsWith('+');\n");
    script.push_str("                    const selector = methodName.substring(1);\n");
    script.push_str("                    const impl = cls[methodName];\n");
    script.push_str("                    if (impl) {\n");
    script.push_str("                        impl.implementation = impl.implementation.clone({\n");
    script.push_str("                            onEnter: function(args) {\n");
    script.push_str("                                if (callCount >= MAX_CALLS) return;\n");
    script.push_str("                                callCount++;\n");
    script.push_str("                                const argTexts = [];\n");
    script.push_str("                                for (let i = 0; i < 4; i++) {\n");
    script.push_str("                                    try {\n");
    script
        .push_str("                                        if (args[i] && !args[i].isNull()) {\n");
    script.push_str(
        "                                            argTexts.push(args[i].toString());\n",
    );
    script.push_str("                                        } else {\n");
    script.push_str("                                            argTexts.push(\"NULL\");\n");
    script.push_str("                                        }\n");
    script.push_str("                                    } catch (e) {\n");
    script.push_str("                                        argTexts.push(\"?\");\n");
    script.push_str("                                    }\n");
    script.push_str("                                }\n");
    script.push_str("                                console.log(\"DAMSEL_FRIDA_CALL \" + cls.$className + \" \" + selector + \" \" + (isClassMethod ? \"+\" : \"-\") + \" \" + argTexts.join(\",\"));\n");
    script.push_str("                            }\n");
    script.push_str("                        });\n");
    script.push_str("                    }\n");
    script.push_str("                } catch (e) { /* skip unhookable */ }\n");
    script.push_str("            }\n");
    script.push_str("        } catch (e) { /* skip untraceable class */ }\n");
    script.push_str("    }\n");
    script.push_str("} else {\n");
    script.push_str("    send({ kind: \"objc_unavailable\" });\n");
    script.push_str("}\n");
    script
}

/// Parse a captured event line into a `MethodCall`.
pub fn parse_event_line(line: &str) -> Option<MethodCall> {
    let rest = line.strip_prefix("DAMSEL_FRIDA_CALL ")?;
    let mut parts = rest.splitn(4, ' ');
    let class_name = parts.next()?.to_string();
    let method_name = parts.next()?.to_string();
    let kind_marker = parts.next()?;
    let is_class_method = kind_marker == "+";
    let args = parts
        .next()
        .map(|raw| raw.split(", ").map(|s| s.to_string()).collect())
        .unwrap_or_default();
    Some(MethodCall {
        class_name,
        method_name,
        is_class_method,
        args,
    })
}

/// Parse a Frida transcript (mixed agent output + our events).
pub fn parse_transcript(transcript: &str) -> FridaReport {
    let mut calls = Vec::new();
    let mut modules = Vec::new();
    for line in transcript.lines() {
        if let Some(call) = parse_event_line(line.trim()) {
            calls.push(call);
            continue;
        }
        // Module list from the objc_available send message.
        if line.contains("\"kind\":\"objc_available\"") {
            // Best-effort: capture module names between [ and ].
            if let (Some(start), Some(end)) = (line.find('['), line.rfind(']')) {
                if start < end {
                    let module_text = &line[start + 1..end];
                    for module in module_text.split(',').map(|s| s.trim().trim_matches('"')) {
                        if !module.is_empty() && module != "kind" {
                            modules.push(module.to_string());
                        }
                    }
                }
            }
        }
    }
    FridaReport {
        target: String::new(),
        calls,
        modules,
    }
}

/// Run a Frida session: spawn the binary, trace ObjC calls for the
/// given duration, and return the parsed report.
pub fn trace_method_calls(
    binary: &Path,
    classes: &[&str],
    duration_secs: u64,
    max_calls: usize,
) -> Result<FridaReport, String> {
    let _ = duration_secs; // v1: frida runs until the target exits
    if !frida_available() {
        return Err("frida not found on PATH; install with `pip install frida-tools`".to_string());
    }
    let script = generate_trace_script(classes, max_calls);
    let script_path =
        std::env::temp_dir().join(format!("damsel-frida-agent-{}.js", std::process::id()));
    std::fs::write(&script_path, &script).map_err(|e| format!("script write: {e}"))?;

    let output = Command::new("frida")
        .arg("--no-pause")
        .arg("-l")
        .arg(&script_path)
        .arg("-f")
        .arg(binary)
        .output();

    let _ = std::fs::remove_file(&script_path);
    let output = output.map_err(|e| format!("failed to run frida: {e}"))?;
    let transcript = String::from_utf8_lossy(&output.stdout).into_owned();
    let mut report = parse_transcript(&transcript);
    report.target = binary.display().to_string();
    Ok(report)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_script_with_class_filter() {
        let script = generate_trace_script(&["Greeter"], 10);
        assert!(script.contains("CLASS_FILTER = [\"Greeter\"]"));
        assert!(script.contains("MAX_CALLS = 10"));
        assert!(script.contains("DAMSEL_FRIDA_CALL"));
    }

    #[test]
    fn parses_event_lines() {
        let call = parse_event_line("DAMSEL_FRIDA_CALL Greeter greeting - 0x1000, 0x2000, NULL, ?")
            .expect("parse");
        assert_eq!(call.class_name, "Greeter");
        assert_eq!(call.method_name, "greeting");
        assert!(!call.is_class_method);
        assert_eq!(call.args.len(), 4);

        let class_method =
            parse_event_line("DAMSEL_FRIDA_CALL Speaker speakerKind + 0x1").expect("parse");
        assert!(class_method.is_class_method);

        assert!(parse_event_line("random lldb noise").is_none());
    }

    #[test]
    fn parses_transcript_with_events_and_modules() {
        let transcript = r#"
DAMSEL_FRIDA_CALL Greeter greeting - 0x1000, 0x2000
{"kind":"objc_available","modules":["Foundation","libobjc.A.dylib"]}
DAMSEL_FRIDA_CALL Speaker init - 0x3000
"#;
        let report = parse_transcript(transcript);
        assert_eq!(report.calls.len(), 2);
        assert_eq!(report.calls[0].class_name, "Greeter");
        assert!(!report.modules.is_empty());
    }
}
